#!/usr/bin/env bash
# A short fish command (picked in the wizard, default `dots`) that runs dotfiles
# recipes from any directory: `dots update`, `dots doctor`, bare `dots` cds to the repo.
# It wraps the `dotfiles` function, so it gets the same tab completion.
. "$(dirname "$0")/lib.sh"
load_state

FN_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/fish/functions"
MARK="# generated by dotfiles scripts/shortcut.sh"

ours() { [ -f "$1" ] && [ ! -L "$1" ] && grep -qxF "$MARK" "$1"; }
clean() { local f; for f in "$FN_DIR"/*.fish; do [ "$(basename "$f" .fish)" = "${1:-}" ] && continue; ours "$f" && rm -f "$f"; done; return 0; }

install() {
  local name="$DOTFILES_SHORTCUT" f
  clean "$name"
  if [ -z "$name" ] || [ "$name" = dotfiles ]; then say "no extra command; 'dotfiles <recipe>' works from anywhere"; return; fi
  f="$FN_DIR/$name.fish"
  if [ -e "$f" ] && ! ours "$f"; then say "$f already exists and isn't ours — pick another name ('just configure')"; return 1; fi
  command -v "$name" >/dev/null 2>&1 && say "note: '$name' shadows $(command -v "$name") in fish"
  mkdir -p "$FN_DIR"
  cat > "$f" <<FISH
$MARK
function $name --wraps dotfiles --description 'run a dotfiles recipe from any directory'
    dotfiles \$argv
end
FISH
  say "'$name <recipe>' runs dotfiles recipes from anywhere (open a new shell)"
}

remove() { clean; say "removed"; }

main "$@"
